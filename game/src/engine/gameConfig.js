export function getDistrictAt(x, z) {
  for (const d of DISTRICTS) {
    if (x >= d.bounds.x0 && x <= d.bounds.x1 && z >= d.bounds.z0 && z <= d.bounds.z1) {
      return d;
    }
  }
  return DISTRICTS[0];
}
